// Спец-цвет '3' там, где производная от цвета ранга читается хуже
export const SPECIAL: Record<string, string> = {
  aspid: '#FFE14D',
  demon: '#FFE14D',
  squid: '#F2F2F2',
  phantom: '#35C759',
  king: '#FF2B4F',
  god: '#FFD700',
}

export const OUTLINE = '#0A0608'

export function shade(hex: string, f: number): string {
  const n = parseInt(hex.slice(1), 16)
  const ch = (v: number) => {
    const m = f < 0 ? v * (1 + f) : v + (255 - v) * f
    return Math.round(Math.min(255, Math.max(0, m)))
  }
  const r = ch((n >> 16) & 255)
  const g = ch((n >> 8) & 255)
  const b = ch(n & 255)
  return `#${((r << 16) | (g << 8) | b).toString(16).padStart(6, '0')}`
}

export default function RankEmblem({
  rank,
  color,
  size = 40,
}: {
  rank: string
  color: string
  size?: number
}) {
  const key = rank.trim().toLowerCase()
  const map = EMBLEMS[key] ?? EMBLEMS.baron
  const palette: Record<string, string> = {
    '0': OUTLINE,
    '1': shade(color, -0.12),
    '2': shade(color, 0.38),
    '3': SPECIAL[key] ?? shade(color, 0.65),
  }

  const rects: React.ReactNode[] = []
  for (let y = 0; y < GRID; y++) {
    const row = map[y]
    if (!row) continue
    for (let x = 0; x < GRID; x++) {
      const c = row[x]
      if (!c || c === '.') continue
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={palette[c]} />)
    }
  }

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${GRID} ${GRID}`}
      shapeRendering="crispEdges"
      style={{ imageRendering: 'pixelated', display: 'block' }}
      role="img"
      aria-label={`Герб ранга ${rank}`}
    >
      {rects}
    </svg>
  )
}
